const I18N = {
  // Get current language from localStorage or browser detect
  getLang() {
    const stored = localStorage.getItem('supplier_language');
    if (stored === 'en' || stored === 'zh') return stored;
    const navLang = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
    if (navLang.startsWith('zh')) return 'zh';
    return 'en';
  },

  // Set language and reload page
  setLang(lang) {
    localStorage.setItem('supplier_language', lang);
    window.location.reload();
  },

  // Get translation string by key path (e.g., 'login.title')
  t(keyPath) {
    const lang = this.getLang();
    const keys = keyPath.split('.');
    let value = TRANSLATIONS[lang];
    for (const key of keys) {
      if (value && typeof value === 'object' && key in value) {
        value = value[key];
      } else {
        // Fallback to English
        value = TRANSLATIONS['en'];
        for (const k of keys) {
          if (value && typeof value === 'object' && k in value) {
            value = value[k];
          } else {
            return keyPath; // Return key path if not found
          }
        }
        return value;
      }
    }
    return typeof value === 'string' ? value : keyPath;
  },

  // Apply translations to all elements with data-i18n attribute
  apply() {
    const lang = this.getLang();
    document.documentElement.lang = lang === 'zh' ? 'zh' : 'en';

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (!key) return;
      const text = this.t(key);
      // Check for placeholder attribute preference
      if (el.hasAttribute('data-i18n-attr')) {
        const attr = el.getAttribute('data-i18n-attr');
        el.setAttribute(attr, text);
      } else {
        el.textContent = text;
      }
    });

    // Update language selector if present
    const selector = document.getElementById('languageSelect');
    if (selector) {
      selector.value = lang;
    }
  },

  // Create language selector HTML
  selectorHtml() {
    const lang = this.getLang();
    return `
      <div class="lang-selector">
        <label for="languageSelect" style="color: white; font-size: 13px;">${this.t('common.language')}:</label>
        <select id="languageSelect" onchange="I18N.setLang(this.value)">
          <option value="en" ${lang === 'en' ? 'selected' : ''}>${this.t('common.en')}</option>
          <option value="zh" ${lang === 'zh' ? 'selected' : ''}>${this.t('common.zh')}</option>
        </select>
      </div>
    `;
  }
};

// Auto-apply on DOM ready if document is already loaded, otherwise wait
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => I18N.apply());
} else {
  I18N.apply();
}
